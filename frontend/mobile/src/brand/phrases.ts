let last: number | null = null;
let current: number | null = null;

/** La frase de esta vez que se abrió la app (al azar y distinta a la anterior). */
export function sessionPhrase(random: () => number = Math.random): string {
  if (current === null) {
    let i = Math.floor(random() * PHRASES.length);
    if (i === last) i = (i + 1) % PHRASES.length;
    current = i;
  }
  return PHRASES[current]!;
}

/** Cambia la frase (al volver a la app después de un rato o al deslizar para actualizar). */
export function nextPhrase(random: () => number = Math.random): string {
  last = current; current = null;
  return sessionPhrase(random);
}

export function _resetPhrases() { last = null; current = null; }
